    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

    String supplierName = txtSupplierName.getText().trim();
    String phone = txtPhone.getText().trim();
    String supplies = txtSupplies.getText().trim();

    if (supplierName.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Supplier Name");
        txtSupplierName.requestFocus();
        return;
    }

    String sql = "INSERT INTO suppliers (SUPPLIER_NAME, PHONE, SUPPLIES) VALUES (?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setString(1, supplierName);
        stmt.setString(2, phone.isEmpty() ? null : phone);
        stmt.setString(3, supplies.isEmpty() ? null : supplies);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Supplier saved successfully!");
        clearFields();
        loadSuppliers();
        currentIndex = -1;

    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

