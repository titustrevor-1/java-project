    private void loadRoomTypes() {
    roomTypesList.clear();
    String sql = "SELECT room_type_id, type_name, base_price, capacity FROM room_types";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            roomTypesList.add(new Object[]{
                rs.getInt("room_type_id"),
                rs.getString("type_name"),
                rs.getBigDecimal("base_price"),
                rs.getInt("capacity")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (roomTypesList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= roomTypesList.size()) index = roomTypesList.size() - 1;
    currentIndex = index;

    Object[] record = roomTypesList.get(currentIndex);
    txtRoomTypeID.setText(String.valueOf(record[0]));
    txtTypeName.setText((String) record[1]);
    txtBasePrice.setText(String.valueOf(record[2]));
    txtCapacity.setText(String.valueOf(record[3]));
}

private void clearFields() {
    txtRoomTypeID.setText("");
    txtTypeName.setText("");
    txtBasePrice.setText("");
    txtCapacity.setText("");
}
