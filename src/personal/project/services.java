    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

    String serviceName = txtServiceName.getText().trim();
    String description = txtDescription.getText().trim();
    String priceStr = txtPrice.getText().trim();

    if (serviceName.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Service Name");
        txtServiceName.requestFocus();
        return;
    }
    if (priceStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Price");
        txtPrice.requestFocus();
        return;
    }

    java.math.BigDecimal price;
    try {
        price = new java.math.BigDecimal(priceStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Price must be a valid number.");
        return;
    }

    String sql = "INSERT INTO services (SERVICE_NAME, DESCRIPTION, PRICE) VALUES (?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setString(1, serviceName);
        stmt.setString(2, description.isEmpty() ? null : description);
        stmt.setBigDecimal(3, price);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Service saved successfully!");
        clearFields();
        loadServices();
        currentIndex = -1;

    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

