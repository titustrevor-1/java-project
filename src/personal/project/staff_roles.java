    private void loadStaffRoles() {
    staffRolesList.clear();
    String sql = "SELECT role_id, role_name FROM staff_roles";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            staffRolesList.add(new Object[]{
                rs.getInt("role_id"),
                rs.getString("role_name")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (staffRolesList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= staffRolesList.size()) index = staffRolesList.size() - 1;
    currentIndex = index;

    Object[] record = staffRolesList.get(currentIndex);
    txtRoleID.setText(String.valueOf(record[0]));
    txtRoleName.setText((String) record[1]);
}

private void clearFields() {
    txtRoleID.setText("");
    txtRoleName.setText("");
}
