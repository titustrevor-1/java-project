    private void loadRoomStatus() {
    roomStatusList.clear();
    String sql = "SELECT status_id, status_name FROM room_status";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            roomStatusList.add(new Object[]{
                rs.getInt("status_id"),
                rs.getString("status_name")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (roomStatusList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= roomStatusList.size()) index = roomStatusList.size() - 1;
    currentIndex = index;

    Object[] record = roomStatusList.get(currentIndex);
    txtStatusID.setText(String.valueOf(record[0]));
    txtStatusName.setText((String) record[1]);
}

private void clearFields() {
    txtStatusID.setText("");
    txtStatusName.setText("");
}
