    private void loadServices() {
    servicesList.clear();
    String sql = "SELECT SERVICE_ID, SERVICE_NAME, DESCRIPTION, PRICE FROM services";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            servicesList.add(new Object[]{
                rs.getInt("SERVICE_ID"),
                rs.getString("SERVICE_NAME"),
                rs.getString("DESCRIPTION"),
                rs.getBigDecimal("PRICE")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (servicesList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= servicesList.size()) index = servicesList.size() - 1;
    currentIndex = index;

    Object[] record = servicesList.get(currentIndex);
    txtServiceID.setText(String.valueOf(record[0]));
    txtServiceName.setText((String) record[1]);
    txtDescription.setText(record[2] == null ? "" : (String) record[2]);
    txtPrice.setText(String.valueOf(record[3]));
}

private void clearFields() {
    txtServiceID.setText("");
    txtServiceName.setText("");
    txtDescription.setText("");
    txtPrice.setText("");
}
