    private void loadMaintenance() {
    maintenanceList.clear();
    String sql = "SELECT maintenance_id, room_id, staff_id, issue_description, reported_date, request_status, resolved_date FROM maintenance_requests";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            maintenanceList.add(new Object[]{
                rs.getInt("maintenance_id"),
                rs.getInt("room_id"),
                rs.getInt("staff_id"),
                rs.getString("issue_description"),
                rs.getDate("reported_date"),
                rs.getString("request_status"),
                rs.getDate("resolved_date")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (maintenanceList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= maintenanceList.size()) index = maintenanceList.size() - 1;
    currentIndex = index;

    Object[] record = maintenanceList.get(currentIndex);
    txtMaintenanceID.setText(String.valueOf(record[0]));
    txtRoomID.setText(String.valueOf(record[1]));
    txtStaffID.setText(String.valueOf(record[2]));
    txtIssueDescription.setText((String) record[3]);
    txtReportedDate.setText(String.valueOf(record[4]));
    txtRequestedStatus.setText((String) record[5]);
    txtResolvedDate.setText(record[6] == null ? "" : String.valueOf(record[6]));
}

