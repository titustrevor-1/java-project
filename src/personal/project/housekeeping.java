    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
    
    String roomIdStr = txtRoomID.getText().trim();
    String staffIdStr = txtStaffID.getText().trim();
    String taskDateStr = txtTaskDate.getText().trim();
    String taskStatus = txtTaskStatus.getText().trim();
    String notes = txtStatus.getText().trim();

    if (roomIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Room ID");
        txtRoomID.requestFocus();
        return;
    }
    if (staffIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Staff ID");
        txtStaffID.requestFocus();
        return;
    }
    if (taskDateStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Task Date (YYYY-MM-DD)");
        txtTaskDate.requestFocus();
        return;
    }
    if (taskStatus.isEmpty()) {
        taskStatus = "Pending"; // matches database default
    }

    int roomId, staffId;
    java.sql.Date taskDate;
    try {
        roomId = Integer.parseInt(roomIdStr);
        staffId = Integer.parseInt(staffIdStr);
        taskDate = java.sql.Date.valueOf(taskDateStr);
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, "Room ID and Staff ID must be numbers; Task Date must be YYYY-MM-DD.");
        return;
    }

    String sql = "INSERT INTO housekeeping (room_id, staff_id, task_date, task_status, notes) VALUES (?, ?, ?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, roomId);
        stmt.setInt(2, staffId);
        stmt.setDate(3, taskDate);
        stmt.setString(4, taskStatus);
        stmt.setString(5, notes.isEmpty() ? null : notes);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Housekeeping task saved successfully!");
        clearFields();
        loadHousekeeping();
        currentIndex = -1;

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        JOptionPane.showMessageDialog(this,
            "Room ID or Staff ID doesn't exist in their tables.",
            "Save Blocked", JOptionPane.WARNING_MESSAGE);
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
 
    String idStr = txtHousekeepingID.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a Housekeeping ID to search");
        txtHousekeepingID.requestFocus();
        return;
    }

    int housekeepingId;
    try {
        housekeepingId = Integer.parseInt(idStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Housekeeping ID must be a number.");
        return;
    }

    String sql = "SELECT housekeeping_id, room_id, staff_id, task_date, task_status, notes FROM housekeeping WHERE housekeeping_id = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, housekeepingId);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtHousekeepingID.setText(String.valueOf(rs.getInt("housekeeping_id")));
                txtRoomID.setText(String.valueOf(rs.getInt("room_id")));
                txtStaffID.setText(String.valueOf(rs.getInt("staff_id")));
                txtTaskDate.setText(String.valueOf(rs.getDate("task_date")));
                txtTaskStatus.setText(rs.getString("task_status"));
                txtStatus.setText(rs.getString("notes") == null ? "" : rs.getString("notes"));
            } else {
                JOptionPane.showMessageDialog(this, "No housekeeping record found with that ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

