    private void btnloginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnloginActionPerformed


    if (loginLocked) {
        JOptionPane.showMessageDialog(this, "Too many failed attempts. Please wait before trying again.");
        return;
    }

    String name = txtusername.getText().trim();
    String password = new String(txtpassword.getPassword()).trim();

    if (name.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter username");
        txtusername.requestFocus();
        return;
    }
    if (password.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter password");
        txtpassword.requestFocus();
        return;
    }

    String sql = "SELECT * FROM users WHERE username = ? AND password = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setString(1, name);
        stmt.setString(2, password);

        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                // Save username for next time
                java.util.prefs.Preferences prefs = java.util.prefs.Preferences.userNodeForPackage(LOG_IN.class);
                prefs.put("lastUsername", name);

                failedAttempts = 0;
                new MENU().Main();
                this.dispose();
            } else {
                failedAttempts++;
                int remaining = MAX_ATTEMPTS - failedAttempts;

                if (remaining <= 0) {
                    loginLocked = true;
                    JOptionPane.showMessageDialog(this, "Too many failed attempts. Login locked for 30 seconds.");
                    btnlogin.setEnabled(false);

                    javax.swing.Timer timer = new javax.swing.Timer(30000, e -> {
                        loginLocked = false;
                        failedAttempts = 0;
                        btnlogin.setEnabled(true);
                        JOptionPane.showMessageDialog(this, "You can try logging in again.");
                    });
                    timer.setRepeats(false);
                    timer.start();
                } else {
                    JOptionPane.showMessageDialog(this, "Invalid username or password. " + remaining + " attempt(s) remaining.");
                }

                txtpassword.setText("");
                txtpassword.requestFocus();
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }


    }//GEN-LAST:event_btnloginActionPerformed

