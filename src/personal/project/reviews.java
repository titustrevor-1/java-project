    private void loadReviews() {
    reviewsList.clear();
    String sql = "SELECT REVIEW_ID, GUEST_ID, ROOM_ID, RATING, COMMENT, REVIEW_DATE FROM reviews";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            reviewsList.add(new Object[]{
                rs.getInt("REVIEW_ID"),
                rs.getInt("GUEST_ID"),
                rs.getInt("ROOM_ID"),
                rs.getInt("RATING"),
                rs.getString("COMMENT"),
                rs.getDate("REVIEW_DATE")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (reviewsList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= reviewsList.size()) index = reviewsList.size() - 1;
    currentIndex = index;

    Object[] record = reviewsList.get(currentIndex);
    txtReviewID.setText(String.valueOf(record[0]));
    txtGuestID.setText(String.valueOf(record[1]));
    txtRoomID.setText(String.valueOf(record[2]));
    txtRating.setText(String.valueOf(record[3]));
    txtComment.setText(record[4] == null ? "" : (String) record[4]);
    txtReviewDate.setText(String.valueOf(record[5]));
}

