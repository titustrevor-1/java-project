    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
      
    String roomIdStr = txtRoomID.getText().trim();
    String staffIdStr = txtStaffID.getText().trim();
    String issueDescription = txtIssueDescription.getText().trim();
    String reportedDateStr = txtReportedDate.getText().trim();
    String status = txtRequestedStatus.getText().trim();
    String resolvedDateStr = txtResolvedDate.getText().trim();

    if (roomIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Room ID");
        txtRoomID.requestFocus();
        return;
    }
    if (staffIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Staff ID");
        txtStaffID.requestFocus();
        return;
    }
    if (issueDescription.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Issue Description");
        txtIssueDescription.requestFocus();
        return;
    }
    if (reportedDateStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Reported Date (YYYY-MM-DD)");
        txtReportedDate.requestFocus();
        return;
    }
    if (status.isEmpty()) {
        status = "Open"; // matches database default
    }

    int roomId, staffId;
    java.sql.Date reportedDate;
    java.sql.Date resolvedDate = null;
    try {
        roomId = Integer.parseInt(roomIdStr);
        staffId = Integer.parseInt(staffIdStr);
        reportedDate = java.sql.Date.valueOf(reportedDateStr);
        if (!resolvedDateStr.isEmpty()) {
            resolvedDate = java.sql.Date.valueOf(resolvedDateStr);
        }
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, "Room ID and Staff ID must be numbers; dates must be YYYY-MM-DD.");
        return;
    }

    String sql = "INSERT INTO maintenance_requests (room_id, staff_id, issue_description, reported_date, request_status, resolved_date) VALUES (?, ?, ?, ?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, roomId);
        stmt.setInt(2, staffId);
        stmt.setString(3, issueDescription);
        stmt.setDate(4, reportedDate);
        stmt.setString(5, status);
        if (resolvedDate == null) stmt.setNull(6, java.sql.Types.DATE); else stmt.setDate(6, resolvedDate);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Maintenance request saved successfully!");
        clearFields();
        loadMaintenance();
        currentIndex = -1;

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        JOptionPane.showMessageDialog(this,
            "Room ID or Staff ID doesn't exist in their tables.",
            "Save Blocked", JOptionPane.WARNING_MESSAGE);
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

