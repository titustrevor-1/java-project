private void loadBookings() {
    bookingList.clear();
    String sql = "SELECT booking_id, guest_id, room_id, created_by, check_in_date, check_out_date, booking_status, total_amount FROM bookings";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            bookingList.add(new Object[]{
                rs.getInt("booking_id"),
                rs.getInt("guest_id"),
                rs.getInt("room_id"),
                rs.getInt("created_by"),
                rs.getDate("check_in_date"),
                rs.getDate("check_out_date"),
                rs.getString("booking_status"),
                rs.getBigDecimal("total_amount")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (bookingList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= bookingList.size()) index = bookingList.size() - 1;
    currentIndex = index;

    Object[] record = bookingList.get(currentIndex);
    txtBookingID.setText(String.valueOf(record[0]));
    txtGuestID.setText(String.valueOf(record[1]));
    txtRoomID.setText(String.valueOf(record[2]));
    txtCreatedBy.setText(String.valueOf(record[3]));
    txtCheckInDate.setText(String.valueOf(record[4]));
    txtCheckOutDate.setText(String.valueOf(record[5]));
    txtBookingStatus.setText(String.valueOf(record[6]));
    txtAmount.setText(String.valueOf(record[7]));
}

