    private void loadPayments() {
    paymentsList.clear();
    String sql = "SELECT payment_id, booking_id, amount, payment_method, payment_date, payment_status FROM payments";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            paymentsList.add(new Object[]{
                rs.getInt("payment_id"),
                rs.getInt("booking_id"),
                rs.getBigDecimal("amount"),
                rs.getString("payment_method"),
                rs.getDate("payment_date"),
                rs.getString("payment_status")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (paymentsList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= paymentsList.size()) index = paymentsList.size() - 1;
    currentIndex = index;

    Object[] record = paymentsList.get(currentIndex);
    txtPaymentID.setText(String.valueOf(record[0]));
    txtBookingID.setText(String.valueOf(record[1]));
    txtAmount.setText(String.valueOf(record[2]));
    txtPaymentMethod.setText((String) record[3]);
    txtPaymentDate.setText(String.valueOf(record[4]));
    txtPaymentStatus.setText((String) record[5]);
}

private void clearFields() {
    txtPaymentID.setText("");
    txtBookingID.setText("");
    txtAmount.setText("");
    txtPaymentMethod.setText("");
    txtPaymentDate.setText("");
    txtPaymentStatus.setText("");
}
