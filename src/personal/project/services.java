    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
 
    String idStr = txtServiceID.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a Service ID to search");
        txtServiceID.requestFocus();
        return;
    }

    int serviceId;
    try {
        serviceId = Integer.parseInt(idStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Service ID must be a number.");
        return;
    }

    String sql = "SELECT SERVICE_ID, SERVICE_NAME, DESCRIPTION, PRICE FROM services WHERE SERVICE_ID = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, serviceId);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtServiceID.setText(String.valueOf(rs.getInt("SERVICE_ID")));
                txtServiceName.setText(rs.getString("SERVICE_NAME"));
                txtDescription.setText(rs.getString("DESCRIPTION") == null ? "" : rs.getString("DESCRIPTION"));
                txtPrice.setText(String.valueOf(rs.getBigDecimal("PRICE")));
            } else {
                JOptionPane.showMessageDialog(this, "No service found with that Service ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

