    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
 
    String idStr = txtStatusID.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a Status ID to search");
        txtStatusID.requestFocus();
        return;
    }

    int statusId;
    try {
        statusId = Integer.parseInt(idStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Status ID must be a number.");
        return;
    }

    String sql = "SELECT status_id, status_name FROM room_status WHERE status_id = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, statusId);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtStatusID.setText(String.valueOf(rs.getInt("status_id")));
                txtStatusName.setText(rs.getString("status_name"));
            } else {
                JOptionPane.showMessageDialog(this, "No status found with that Status ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

