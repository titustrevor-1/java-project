    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
 
    String itemName = txtItemName.getText().trim();
    String quantityStr = txtQuantity.getText().trim();
    String unit = txtUnit.getText().trim();
    String reorderStr = txtReorderLevel.getText().trim();
    String supplierStr = txtSupplierID.getText().trim();

    if (itemName.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Item Name");
        txtItemName.requestFocus();
        return;
    }
    if (quantityStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Quantity");
        txtQuantity.requestFocus();
        return;
    }

    int quantity;
    Integer reorderLevel = null;
    Integer supplierId = null;
    try {
        quantity = Integer.parseInt(quantityStr);
        if (!reorderStr.isEmpty()) {
            reorderLevel = Integer.parseInt(reorderStr);
        }
        if (!supplierStr.isEmpty()) {
            supplierId = Integer.parseInt(supplierStr);
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Quantity, Reorder Level, and Supplier ID must be numbers.");
        return;
    }

    String sql = "INSERT INTO inventory (ITEM_NAME, QUANTITY, UNIT, REORDER_LEVEL, SUPPLIER_ID) VALUES (?, ?, ?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setString(1, itemName);
        stmt.setInt(2, quantity);
        stmt.setString(3, unit.isEmpty() ? null : unit);
        if (reorderLevel == null) stmt.setNull(4, java.sql.Types.INTEGER); else stmt.setInt(4, reorderLevel);
        if (supplierId == null) stmt.setNull(5, java.sql.Types.INTEGER); else stmt.setInt(5, supplierId);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Item saved successfully!");
        clearFields();
        loadInventory();
        currentIndex = -1;

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        JOptionPane.showMessageDialog(this,
            "Supplier ID doesn't exist in the suppliers table.",
            "Save Blocked", JOptionPane.WARNING_MESSAGE);
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
 
    String idStr = txtInventoryID.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter an Inventory ID to search");
        txtInventoryID.requestFocus();
        return;
    }

    int inventoryId;
    try {
        inventoryId = Integer.parseInt(idStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Inventory ID must be a number.");
        return;
    }

    String sql = "SELECT INVENTORY_ID, ITEM_NAME, QUANTITY, UNIT, REORDER_LEVEL, SUPPLIER_ID FROM inventory WHERE INVENTORY_ID = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, inventoryId);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtInventoryID.setText(String.valueOf(rs.getInt("INVENTORY_ID")));
                txtItemName.setText(rs.getString("ITEM_NAME"));
                txtQuantity.setText(String.valueOf(rs.getInt("QUANTITY")));
                txtUnit.setText(rs.getString("UNIT") == null ? "" : rs.getString("UNIT"));
                Object reorder = rs.getObject("REORDER_LEVEL");
                txtReorderLevel.setText(reorder == null ? "" : String.valueOf(reorder));
                Object supplier = rs.getObject("SUPPLIER_ID");
                txtSupplierID.setText(supplier == null ? "" : String.valueOf(supplier));
            } else {
                JOptionPane.showMessageDialog(this, "No item found with that Inventory ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

