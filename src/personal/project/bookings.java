    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

    String guestIdStr = txtGuestID.getText().trim();
    String roomIdStr = txtRoomID.getText().trim();
    String createdByStr = txtCreatedBy.getText().trim();
    String checkInStr = txtCheckInDate.getText().trim();
    String checkOutStr = txtCheckOutDate.getText().trim();
    String status = txtBookingStatus.getText().trim();
    String amountStr = txtAmount.getText().trim();

    if (guestIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Guest ID");
        txtGuestID.requestFocus();
        return;
    }
    if (roomIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Room ID");
        txtRoomID.requestFocus();
        return;
    }
    if (createdByStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Created By (staff ID)");
        txtCreatedBy.requestFocus();
        return;
    }
    if (checkInStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Check-In Date (YYYY-MM-DD)");
        txtCheckInDate.requestFocus();
        return;
    }
    if (checkOutStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Check-Out Date (YYYY-MM-DD)");
        txtCheckOutDate.requestFocus();
        return;
    }
    if (status.isEmpty()) {
        status = "Confirmed"; // matches the database default
    }
    if (amountStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Total Amount");
        txtAmount.requestFocus();
        return;
    }

    int guestId, roomId, createdBy;
    java.sql.Date checkIn, checkOut;
    java.math.BigDecimal amount;
    try {
        guestId = Integer.parseInt(guestIdStr);
        roomId = Integer.parseInt(roomIdStr);
        createdBy = Integer.parseInt(createdByStr);
        checkIn = java.sql.Date.valueOf(checkInStr);
        checkOut = java.sql.Date.valueOf(checkOutStr);
        amount = new java.math.BigDecimal(amountStr);
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, "Check your entries: IDs must be numbers, dates must be YYYY-MM-DD, amount must be a number.");
        return;
    }

    String sql = "INSERT INTO bookings (guest_id, room_id, created_by, check_in_date, check_out_date, booking_status, total_amount) VALUES (?, ?, ?, ?, ?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, guestId);
        stmt.setInt(2, roomId);
        stmt.setInt(3, createdBy);
        stmt.setDate(4, checkIn);
        stmt.setDate(5, checkOut);
        stmt.setString(6, status);
        stmt.setBigDecimal(7, amount);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Booking saved successfully!");
        clearFields();
        loadBookings();
        currentIndex = -1;

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        JOptionPane.showMessageDialog(this,
            "Guest ID, Room ID, or Created By doesn't exist in their tables.",
            "Save Blocked", JOptionPane.WARNING_MESSAGE);
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

