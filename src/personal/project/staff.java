    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
  
    String idStr = txtStaffID.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a Staff ID to search");
        txtStaffID.requestFocus();
        return;
    }

    int staffId;
    try {
        staffId = Integer.parseInt(idStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Staff ID must be a number.");
        return;
    }

    String sql = "SELECT staff_id, full_name, phone, email, role_id, hire_date, salary FROM staff WHERE staff_id = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, staffId);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtStaffID.setText(String.valueOf(rs.getInt("staff_id")));
                txtFullName.setText(rs.getString("full_name"));
                txtPhone.setText(rs.getString("phone"));
                txtEmail.setText(rs.getString("email") == null ? "" : rs.getString("email"));
                txtRoleID.setText(String.valueOf(rs.getInt("role_id")));
                txtHireDate.setText(String.valueOf(rs.getDate("hire_date")));
                txtSalary.setText(String.valueOf(rs.getBigDecimal("salary")));
            } else {
                JOptionPane.showMessageDialog(this, "No staff found with that Staff ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

