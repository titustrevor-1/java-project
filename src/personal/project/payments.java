    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
 
    String idStr = txtPaymentID.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a Payment ID to search");
        txtPaymentID.requestFocus();
        return;
    }

    int paymentId;
    try {
        paymentId = Integer.parseInt(idStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Payment ID must be a number.");
        return;
    }

    String sql = "SELECT payment_id, booking_id, amount, payment_method, payment_date, payment_status FROM payments WHERE payment_id = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, paymentId);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtPaymentID.setText(String.valueOf(rs.getInt("payment_id")));
                txtBookingID.setText(String.valueOf(rs.getInt("booking_id")));
                txtAmount.setText(String.valueOf(rs.getBigDecimal("amount")));
                txtPaymentMethod.setText(rs.getString("payment_method"));
                txtPaymentDate.setText(String.valueOf(rs.getDate("payment_date")));
                txtPaymentStatus.setText(rs.getString("payment_status"));
            } else {
                JOptionPane.showMessageDialog(this, "No payment found with that Payment ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

