    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
    
    String idStr = txtReviewID.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a Review ID to search");
        txtReviewID.requestFocus();
        return;
    }

    int reviewId;
    try {
        reviewId = Integer.parseInt(idStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Review ID must be a number.");
        return;
    }

    String sql = "SELECT REVIEW_ID, GUEST_ID, ROOM_ID, RATING, COMMENT, REVIEW_DATE FROM reviews WHERE REVIEW_ID = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, reviewId);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtReviewID.setText(String.valueOf(rs.getInt("REVIEW_ID")));
                txtGuestID.setText(String.valueOf(rs.getInt("GUEST_ID")));
                txtRoomID.setText(String.valueOf(rs.getInt("ROOM_ID")));
                txtRating.setText(String.valueOf(rs.getInt("RATING")));
                txtComment.setText(rs.getString("COMMENT") == null ? "" : rs.getString("COMMENT"));
                txtReviewDate.setText(String.valueOf(rs.getDate("REVIEW_DATE")));
            } else {
                JOptionPane.showMessageDialog(this, "No review found with that Review ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

