    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
  
    String guestIdStr = txtGuestID.getText().trim();
    String serviceIdStr = txtServiceID.getText().trim();
    String staffIdStr = txtStaffID.getText().trim();
    String bookingDateStr = txtBookingDate.getText().trim();
    String quantityStr = txtQuantity.getText().trim();
    String amountStr = txtTotalAmount.getText().trim();

    if (guestIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Guest ID");
        txtGuestID.requestFocus();
        return;
    }
    if (serviceIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Service ID");
        txtServiceID.requestFocus();
        return;
    }
    if (bookingDateStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Booking Date (YYYY-MM-DD)");
        txtBookingDate.requestFocus();
        return;
    }

    int guestId, serviceId;
    Integer staffId = null;
    Integer quantity = null;
    java.sql.Date bookingDate;
    java.math.BigDecimal amount = null;
    try {
        guestId = Integer.parseInt(guestIdStr);
        serviceId = Integer.parseInt(serviceIdStr);
        bookingDate = java.sql.Date.valueOf(bookingDateStr);
        if (!staffIdStr.isEmpty()) staffId = Integer.parseInt(staffIdStr);
        if (!quantityStr.isEmpty()) quantity = Integer.parseInt(quantityStr);
        if (!amountStr.isEmpty()) amount = new java.math.BigDecimal(amountStr);
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, "IDs and Quantity must be numbers; Date must be YYYY-MM-DD; Amount must be a valid number.");
        return;
    }

    String sql = "INSERT INTO service_bookings (GUEST_ID, SERVICE_ID, STAFF_ID, BOOKING_DATE, QUANTITY, TOTAL_AMOUNT) VALUES (?, ?, ?, ?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, guestId);
        stmt.setInt(2, serviceId);
        if (staffId == null) stmt.setNull(3, java.sql.Types.INTEGER); else stmt.setInt(3, staffId);
        stmt.setDate(4, bookingDate);
        if (quantity == null) stmt.setNull(5, java.sql.Types.INTEGER); else stmt.setInt(5, quantity);
        if (amount == null) stmt.setNull(6, java.sql.Types.DECIMAL); else stmt.setBigDecimal(6, amount);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Service booking saved successfully!");
        clearFields();
        loadServiceBookings();
        currentIndex = -1;

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        JOptionPane.showMessageDialog(this,
            "Guest ID, Service ID, or Staff ID doesn't exist in their tables.",
            "Save Blocked", JOptionPane.WARNING_MESSAGE);
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

