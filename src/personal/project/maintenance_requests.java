    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
    
    String idStr = txtMaintenanceID.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a Maintenance ID to search");
        txtMaintenanceID.requestFocus();
        return;
    }

    int maintenanceId;
    try {
        maintenanceId = Integer.parseInt(idStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Maintenance ID must be a number.");
        return;
    }

    String sql = "SELECT maintenance_id, room_id, staff_id, issue_description, reported_date, request_status, resolved_date FROM maintenance_requests WHERE maintenance_id = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, maintenanceId);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtMaintenanceID.setText(String.valueOf(rs.getInt("maintenance_id")));
                txtRoomID.setText(String.valueOf(rs.getInt("room_id")));
                txtStaffID.setText(String.valueOf(rs.getInt("staff_id")));
                txtIssueDescription.setText(rs.getString("issue_description"));
                txtReportedDate.setText(String.valueOf(rs.getDate("reported_date")));
                txtRequestedStatus.setText(rs.getString("request_status"));
                java.sql.Date resolved = rs.getDate("resolved_date");
                txtResolvedDate.setText(resolved == null ? "" : String.valueOf(resolved));
            } else {
                JOptionPane.showMessageDialog(this, "No maintenance request found with that ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

