    private void btnforgotpasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnforgotpasswordActionPerformed

    String name = JOptionPane.showInputDialog(this, "Enter your username:");
    if (name == null || name.trim().isEmpty()) {
        return;
    }
    name = name.trim();

    String checkSql = "SELECT COUNT(*) FROM users WHERE username = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement checkStmt = conn.prepareStatement(checkSql)) {

        checkStmt.setString(1, name);
        try (java.sql.ResultSet rs = checkStmt.executeQuery()) {
            rs.next();
            if (rs.getInt(1) == 0) {
                JOptionPane.showMessageDialog(this, "No account found with that username.");
                return;
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        return;
    }

    String newPassword = JOptionPane.showInputDialog(this, "Enter a new password:");
    if (newPassword == null || newPassword.trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Password reset cancelled.");
        return;
    }

    String updateSql = "UPDATE users SET password = ? WHERE username = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement updateStmt = conn.prepareStatement(updateSql)) {

        updateStmt.setString(1, newPassword.trim());
        updateStmt.setString(2, name);
        updateStmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Password updated successfully. You can now log in.");
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnforgotpasswordActionPerformed

