    private void loadSuppliers() {
    suppliersList.clear();
    String sql = "SELECT SUPPLIER_ID, SUPPLIER_NAME, PHONE, SUPPLIES FROM suppliers";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            suppliersList.add(new Object[]{
                rs.getInt("SUPPLIER_ID"),
                rs.getString("SUPPLIER_NAME"),
                rs.getString("PHONE"),
                rs.getString("SUPPLIES")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (suppliersList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= suppliersList.size()) index = suppliersList.size() - 1;
    currentIndex = index;

    Object[] record = suppliersList.get(currentIndex);
    txtSupplierID.setText(String.valueOf(record[0]));
    txtSupplierName.setText((String) record[1]);
    txtPhone.setText(record[2] == null ? "" : (String) record[2]);
    txtSupplies.setText(record[3] == null ? "" : (String) record[3]);
}

private void clearFields() {
    txtSupplierID.setText("");
    txtSupplierName.setText("");
    txtPhone.setText("");
    txtSupplies.setText("");
}
