    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

    String fullName = txtFullName.getText().trim();
    String phone = txtPhone.getText().trim();
    String email = txtEmail.getText().trim();
    String roleIdStr = txtRoleID.getText().trim();
    String hireDateStr = txtHireDate.getText().trim();
    String salaryStr = txtSalary.getText().trim();

    if (fullName.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Full Name");
        txtFullName.requestFocus();
        return;
    }
    if (phone.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Phone");
        txtPhone.requestFocus();
        return;
    }
    if (roleIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Role ID");
        txtRoleID.requestFocus();
        return;
    }
    if (hireDateStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Hire Date (YYYY-MM-DD)");
        txtHireDate.requestFocus();
        return;
    }
    if (salaryStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Salary");
        txtSalary.requestFocus();
        return;
    }

    int roleId;
    java.sql.Date hireDate;
    java.math.BigDecimal salary;
    try {
        roleId = Integer.parseInt(roleIdStr);
        hireDate = java.sql.Date.valueOf(hireDateStr);
        salary = new java.math.BigDecimal(salaryStr);
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, "Role ID and Salary must be numbers; Date must be YYYY-MM-DD.");
        return;
    }

    String sql = "INSERT INTO staff (full_name, phone, email, role_id, hire_date, salary) VALUES (?, ?, ?, ?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setString(1, fullName);
        stmt.setString(2, phone);
        stmt.setString(3, email.isEmpty() ? null : email);
        stmt.setInt(4, roleId);
        stmt.setDate(5, hireDate);
        stmt.setBigDecimal(6, salary);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Staff saved successfully!");
        clearFields();
        loadStaff();
        currentIndex = -1;

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        JOptionPane.showMessageDialog(this,
            "That phone/email is already used, or the Role ID doesn't exist.",
            "Save Blocked", JOptionPane.WARNING_MESSAGE);
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

