    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
 
    String idStr = txtServiceBookingID.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a Service Booking ID to search");
        txtServiceBookingID.requestFocus();
        return;
    }

    int id;
    try {
        id = Integer.parseInt(idStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Service Booking ID must be a number.");
        return;
    }

    String sql = "SELECT SERVICE_BOOKING_ID, GUEST_ID, SERVICE_ID, STAFF_ID, BOOKING_DATE, QUANTITY, TOTAL_AMOUNT FROM service_bookings WHERE SERVICE_BOOKING_ID = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, id);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtServiceBookingID.setText(String.valueOf(rs.getInt("SERVICE_BOOKING_ID")));
                txtGuestID.setText(String.valueOf(rs.getInt("GUEST_ID")));
                txtServiceID.setText(String.valueOf(rs.getInt("SERVICE_ID")));
                Object staff = rs.getObject("STAFF_ID");
                txtStaffID.setText(staff == null ? "" : String.valueOf(staff));
                txtBookingDate.setText(String.valueOf(rs.getDate("BOOKING_DATE")));
                Object qty = rs.getObject("QUANTITY");
                txtQuantity.setText(qty == null ? "" : String.valueOf(qty));
                java.math.BigDecimal amount = rs.getBigDecimal("TOTAL_AMOUNT");
                txtTotalAmount.setText(amount == null ? "" : String.valueOf(amount));
            } else {
                JOptionPane.showMessageDialog(this, "No service booking found with that ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

