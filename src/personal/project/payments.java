    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

    String bookingIdStr = txtBookingID.getText().trim();
    String amountStr = txtAmount.getText().trim();
    String paymentMethod = txtPaymentMethod.getText().trim();
    String paymentDateStr = txtPaymentDate.getText().trim();
    String status = txtPaymentStatus.getText().trim();

    if (bookingIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Booking ID");
        txtBookingID.requestFocus();
        return;
    }
    if (amountStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Amount");
        txtAmount.requestFocus();
        return;
    }
    if (paymentMethod.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Payment Method");
        txtPaymentMethod.requestFocus();
        return;
    }
    if (paymentDateStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Payment Date (YYYY-MM-DD)");
        txtPaymentDate.requestFocus();
        return;
    }
    if (status.isEmpty()) {
        status = "Paid"; // matches database default
    }

    int bookingId;
    java.math.BigDecimal amount;
    java.sql.Date paymentDate;
    try {
        bookingId = Integer.parseInt(bookingIdStr);
        amount = new java.math.BigDecimal(amountStr);
        paymentDate = java.sql.Date.valueOf(paymentDateStr);
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, "Booking ID and Amount must be numbers; Date must be YYYY-MM-DD.");
        return;
    }

    String sql = "INSERT INTO payments (booking_id, amount, payment_method, payment_date, payment_status) VALUES (?, ?, ?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, bookingId);
        stmt.setBigDecimal(2, amount);
        stmt.setString(3, paymentMethod);
        stmt.setDate(4, paymentDate);
        stmt.setString(5, status);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Payment saved successfully!");
        clearFields();
        loadPayments();
        currentIndex = -1;

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        JOptionPane.showMessageDialog(this,
            "Booking ID doesn't exist in the bookings table.",
            "Save Blocked", JOptionPane.WARNING_MESSAGE);
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

