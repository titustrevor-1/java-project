    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

    String guestIdStr = txtGuestID.getText().trim();
    String roomIdStr = txtRoomID.getText().trim();
    String ratingStr = txtRating.getText().trim();
    String comment = txtComment.getText().trim();
    String reviewDateStr = txtReviewDate.getText().trim();

    if (guestIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Guest ID");
        txtGuestID.requestFocus();
        return;
    }
    if (roomIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Room ID");
        txtRoomID.requestFocus();
        return;
    }
    if (ratingStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Rating");
        txtRating.requestFocus();
        return;
    }
    if (reviewDateStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Review Date (YYYY-MM-DD)");
        txtReviewDate.requestFocus();
        return;
    }

    int guestId, roomId, rating;
    java.sql.Date reviewDate;
    try {
        guestId = Integer.parseInt(guestIdStr);
        roomId = Integer.parseInt(roomIdStr);
        rating = Integer.parseInt(ratingStr);
        reviewDate = java.sql.Date.valueOf(reviewDateStr);
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, "Guest ID, Room ID, and Rating must be numbers; Date must be YYYY-MM-DD.");
        return;
    }

    String sql = "INSERT INTO reviews (GUEST_ID, ROOM_ID, RATING, COMMENT, REVIEW_DATE) VALUES (?, ?, ?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, guestId);
        stmt.setInt(2, roomId);
        stmt.setInt(3, rating);
        stmt.setString(4, comment.isEmpty() ? null : comment);
        stmt.setDate(5, reviewDate);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Review saved successfully!");
        clearFields();
        loadReviews();
        currentIndex = -1;

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        JOptionPane.showMessageDialog(this,
            "Guest ID or Room ID doesn't exist in their tables.",
            "Save Blocked", JOptionPane.WARNING_MESSAGE);
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

