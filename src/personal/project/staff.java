    private void loadStaff() {
    staffList.clear();
    String sql = "SELECT staff_id, full_name, phone, email, role_id, hire_date, salary FROM staff";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            staffList.add(new Object[]{
                rs.getInt("staff_id"),
                rs.getString("full_name"),
                rs.getString("phone"),
                rs.getString("email"),
                rs.getInt("role_id"),
                rs.getDate("hire_date"),
                rs.getBigDecimal("salary")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (staffList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= staffList.size()) index = staffList.size() - 1;
    currentIndex = index;

    Object[] record = staffList.get(currentIndex);
    txtStaffID.setText(String.valueOf(record[0]));
    txtFullName.setText((String) record[1]);
    txtPhone.setText((String) record[2]);
    txtEmail.setText(record[3] == null ? "" : (String) record[3]);
    txtRoleID.setText(String.valueOf(record[4]));
    txtHireDate.setText(String.valueOf(record[5]));
    txtSalary.setText(String.valueOf(record[6]));
}

