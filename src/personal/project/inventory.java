    private void loadInventory() {
    inventoryList.clear();
    String sql = "SELECT INVENTORY_ID, ITEM_NAME, QUANTITY, UNIT, REORDER_LEVEL, SUPPLIER_ID FROM inventory";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            inventoryList.add(new Object[]{
                rs.getInt("INVENTORY_ID"),
                rs.getString("ITEM_NAME"),
                rs.getInt("QUANTITY"),
                rs.getString("UNIT"),
                rs.getObject("REORDER_LEVEL"),
                rs.getObject("SUPPLIER_ID")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (inventoryList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= inventoryList.size()) index = inventoryList.size() - 1;
    currentIndex = index;

    Object[] record = inventoryList.get(currentIndex);
    txtInventoryID.setText(String.valueOf(record[0]));
    txtItemName.setText((String) record[1]);
    txtQuantity.setText(String.valueOf(record[2]));
    txtUnit.setText(record[3] == null ? "" : (String) record[3]);
    txtReorderLevel.setText(record[4] == null ? "" : String.valueOf(record[4]));
    txtSupplierID.setText(record[5] == null ? "" : String.valueOf(record[5]));
}

