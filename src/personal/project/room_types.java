    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
   
    String typeName = txtTypeName.getText().trim();
    String basePriceStr = txtBasePrice.getText().trim();
    String capacityStr = txtCapacity.getText().trim();

    if (typeName.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Type Name");
        txtTypeName.requestFocus();
        return;
    }
    if (basePriceStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Base Price");
        txtBasePrice.requestFocus();
        return;
    }
    if (capacityStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter the Capacity");
        txtCapacity.requestFocus();
        return;
    }

    java.math.BigDecimal basePrice;
    int capacity;
    try {
        basePrice = new java.math.BigDecimal(basePriceStr);
        capacity = Integer.parseInt(capacityStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Base Price and Capacity must be numbers.");
        return;
    }

    String sql = "INSERT INTO room_types (type_name, base_price, capacity) VALUES (?, ?, ?)";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setString(1, typeName);
        stmt.setBigDecimal(2, basePrice);
        stmt.setInt(3, capacity);
        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Room type saved successfully!");
        clearFields();
        loadRoomTypes();
        currentIndex = -1;

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        JOptionPane.showMessageDialog(this,
            "That type name already exists.",
            "Save Blocked", JOptionPane.WARNING_MESSAGE);
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnSaveActionPerformed

