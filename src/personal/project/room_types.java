    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
   
    String idStr = txtRoomTypeID.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a Room Type ID to search");
        txtRoomTypeID.requestFocus();
        return;
    }

    int roomTypeId;
    try {
        roomTypeId = Integer.parseInt(idStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Room Type ID must be a number.");
        return;
    }

    String sql = "SELECT room_type_id, type_name, base_price, capacity FROM room_types WHERE room_type_id = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, roomTypeId);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtRoomTypeID.setText(String.valueOf(rs.getInt("room_type_id")));
                txtTypeName.setText(rs.getString("type_name"));
                txtBasePrice.setText(String.valueOf(rs.getBigDecimal("base_price")));
                txtCapacity.setText(String.valueOf(rs.getInt("capacity")));
            } else {
                JOptionPane.showMessageDialog(this, "No room type found with that ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

