    private void loadHousekeeping() {
    housekeepingList.clear();
    String sql = "SELECT housekeeping_id, room_id, staff_id, task_date, task_status, notes FROM housekeeping";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            housekeepingList.add(new Object[]{
                rs.getInt("housekeeping_id"),
                rs.getInt("room_id"),
                rs.getInt("staff_id"),
                rs.getDate("task_date"),
                rs.getString("task_status"),
                rs.getString("notes")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
   
 }



private void showRecord(int index) {
    if (housekeepingList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= housekeepingList.size()) index = housekeepingList.size() - 1;
    currentIndex = index;

    Object[] record = housekeepingList.get(currentIndex);
    txtHousekeepingID.setText(String.valueOf(record[0]));
    txtRoomID.setText(String.valueOf(record[1]));
    txtStaffID.setText(String.valueOf(record[2]));
    txtTaskDate.setText(String.valueOf(record[3]));
    txtTaskStatus.setText(String.valueOf(record[4]));
    txtStatus.setText(record[5] == null ? "" : (String) record[5]);
}

