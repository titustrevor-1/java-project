    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed

    String bookingIdStr = txtBookingID.getText().trim();
    if (bookingIdStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a Booking ID to search");
        txtBookingID.requestFocus();
        return;
    }

    int bookingId;
    try {
        bookingId = Integer.parseInt(bookingIdStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Booking ID must be a number.");
        return;
    }

    String sql = "SELECT booking_id, guest_id, room_id, created_by, check_in_date, check_out_date, booking_status, total_amount FROM bookings WHERE booking_id = ?";
    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, bookingId);
        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtBookingID.setText(String.valueOf(rs.getInt("booking_id")));
                txtGuestID.setText(String.valueOf(rs.getInt("guest_id")));
                txtRoomID.setText(String.valueOf(rs.getInt("room_id")));
                txtCreatedBy.setText(String.valueOf(rs.getInt("created_by")));
                txtCheckInDate.setText(String.valueOf(rs.getDate("check_in_date")));
                txtCheckOutDate.setText(String.valueOf(rs.getDate("check_out_date")));
                txtBookingStatus.setText(rs.getString("booking_status"));
                txtAmount.setText(String.valueOf(rs.getBigDecimal("total_amount")));
            } else {
                JOptionPane.showMessageDialog(this, "No booking found with that Booking ID.");
            }
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnFindActionPerformed

