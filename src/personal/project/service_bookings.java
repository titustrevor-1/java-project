    private void loadServiceBookings() {
    serviceBookingsList.clear();
    String sql = "SELECT SERVICE_BOOKING_ID, GUEST_ID, SERVICE_ID, STAFF_ID, BOOKING_DATE, QUANTITY, TOTAL_AMOUNT FROM service_bookings";

    try (java.sql.Connection conn = DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            serviceBookingsList.add(new Object[]{
                rs.getInt("SERVICE_BOOKING_ID"),
                rs.getInt("GUEST_ID"),
                rs.getInt("SERVICE_ID"),
                rs.getObject("STAFF_ID"),
                rs.getDate("BOOKING_DATE"),
                rs.getObject("QUANTITY"),
                rs.getBigDecimal("TOTAL_AMOUNT")
            });
        }
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void showRecord(int index) {
    if (serviceBookingsList.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No records found.");
        return;
    }
    if (index < 0) index = 0;
    if (index >= serviceBookingsList.size()) index = serviceBookingsList.size() - 1;
    currentIndex = index;

    Object[] record = serviceBookingsList.get(currentIndex);
    txtServiceBookingID.setText(String.valueOf(record[0]));
    txtGuestID.setText(String.valueOf(record[1]));
    txtServiceID.setText(String.valueOf(record[2]));
    txtStaffID.setText(record[3] == null ? "" : String.valueOf(record[3]));
    txtBookingDate.setText(String.valueOf(record[4]));
    txtQuantity.setText(record[5] == null ? "" : String.valueOf(record[5]));
    txtTotalAmount.setText(record[6] == null ? "" : String.valueOf(record[6]));
}

